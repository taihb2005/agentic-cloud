CREATE EXTENSION IF NOT EXISTS ltree;

CREATE TABLE fs_node_permission
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    code        VARCHAR(20)                             NOT NULL,
    description VARCHAR(255),
    CONSTRAINT pk_fs_node_permission PRIMARY KEY (id)
);

CREATE TABLE fs_node_share_user
(
    id            UUID                        NOT NULL,
    node_id       BIGINT                      NOT NULL,
    user_id       UUID                        NOT NULL,
    permission_id BIGINT                      NOT NULL,
    granted_by    UUID                        NOT NULL,
    created_at    TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_fs_node_share_user PRIMARY KEY (id)
);

CREATE TABLE fs_nodes
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id             UUID                                    NOT NULL,
    path                LTREE,
    parent_id           BIGINT,
    name                VARCHAR(255)                            NOT NULL,
    is_folder           BOOLEAN                                 NOT NULL,
    node_status         VARCHAR(20),
    storage_bucket_name VARCHAR(100),
    s3_object_key       VARCHAR(500),
    mime_type           VARCHAR(120),
    size_bytes          BIGINT,
    etag                VARCHAR(100),
    is_starred          BOOLEAN                                 NOT NULL,
    created_at          TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    updated_at          TIMESTAMP WITHOUT TIME ZONE,
    deleted_at          TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_fs_nodes PRIMARY KEY (id)
);

CREATE TABLE fs_shares
(
    id               UUID                        NOT NULL,
    node_id          BIGINT                      NOT NULL,
    created_by       UUID                        NOT NULL,
    is_public        BOOLEAN                     NOT NULL,
    shared_url       VARCHAR(500),
    expires_at       TIMESTAMP WITHOUT TIME ZONE,
    max_access_count INTEGER,
    access_count     INTEGER,
    status           VARCHAR(20),
    created_at       TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_fs_shares PRIMARY KEY (id)
);

CREATE TABLE fs_users
(
    id                          UUID         NOT NULL,
    storage_prefix              VARCHAR(255) NOT NULL,
    storage_bucket_name         VARCHAR(255),
    storage_max_quota_bytes     BIGINT,
    storage_current_quota_bytes BIGINT,
    created_at                  TIMESTAMP WITHOUT TIME ZONE,
    updated_at                  TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_fs_users PRIMARY KEY (id)
);

ALTER TABLE fs_node_permission
    ADD CONSTRAINT uc_fs_node_permission_code UNIQUE (code);

ALTER TABLE fs_shares
    ADD CONSTRAINT uc_fs_shares_node UNIQUE (node_id);

ALTER TABLE fs_nodes
    ADD CONSTRAINT uq_fs_nodes_parent_id_name UNIQUE (parent_id, name);

CREATE INDEX idx_node_browse ON fs_nodes (user_id, parent_id, is_folder, name);

CREATE INDEX idx_share_users_user_id ON fs_node_share_user (user_id);

ALTER TABLE fs_nodes
    ADD CONSTRAINT FK_FS_NODES_ON_PARENT FOREIGN KEY (parent_id) REFERENCES fs_nodes (id);

ALTER TABLE fs_nodes
    ADD CONSTRAINT FK_FS_NODES_ON_USER FOREIGN KEY (user_id) REFERENCES fs_users (id);

ALTER TABLE fs_node_share_user
    ADD CONSTRAINT FK_FS_NODE_SHARE_USER_ON_NODE FOREIGN KEY (node_id) REFERENCES fs_nodes (id);

CREATE INDEX idx_share_users_node_id ON fs_node_share_user (node_id);

ALTER TABLE fs_node_share_user
    ADD CONSTRAINT FK_FS_NODE_SHARE_USER_ON_PERMISSION FOREIGN KEY (permission_id) REFERENCES fs_node_permission (id);

ALTER TABLE fs_shares
    ADD CONSTRAINT FK_FS_SHARES_ON_NODE FOREIGN KEY (node_id) REFERENCES fs_nodes (id);

CREATE INDEX idx_fs_nodes_path_gist ON fs_nodes USING GIST (path);

CREATE INDEX idx_fs_nodes_path_btree ON fs_nodes USING BTREE (path);